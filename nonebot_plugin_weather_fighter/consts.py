def weather_name(code: int) -> str:
    return WEATHER_NAMES.get(code, f"码 {code}")


def weather_score(code: int) -> float:
    """天气码对应的舒适度分值，供省份与区域指数共用。"""
    return WEATHER_SCORES.get(code, 60.0)


def weather_icon(code: int) -> str:
    return WEATHER_ICONS.get(code, "🌡")


def wind_level(gust: float) -> int:
    """把阵风 m/s 粗换成风力等级，给玩家一个直观数字。"""
    thresholds = (0.3, 1.6, 3.4, 5.5, 8.0, 10.8, 13.9, 17.2, 20.8, 24.5, 28.5, 32.7)
    for level, limit in enumerate(thresholds):
        if gust < limit:
            return level
    return 12
